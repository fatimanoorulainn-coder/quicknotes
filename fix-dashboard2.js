var fs = require('fs');
var c = [];
c.push("'use client'");
c.push("import { useEffect, useState } from 'react'");
c.push("import { createClient } from '@/lib/supabase/client'");
c.push("import { useRouter } from 'next/navigation'");
c.push("import ActivityCanvas from '@/app/components/ActivityCanvas'");
c.push("export default function Dashboard() {");
c.push("  const [notes, setNotes] = useState([])");
c.push("  const [title, setTitle] = useState('')");
c.push("  const [content, setContent] = useState('')");
c.push("  const [editing, setEditing] = useState(null)");
c.push("  const [loading, setLoading] = useState(false)");
c.push("  const [toasts, setToasts] = useState([])");
c.push("  const [events, setEvents] = useState([])");
c.push("  const supabase = createClient()");
c.push("  const router = useRouter()");
c.push("  function addToast(msg, type) {");
c.push("    if (!type) type = 'success'");
c.push("    const id = Date.now()");
c.push("    setToasts(function(p) { return [...p, {id, message: msg, type}] })");
c.push("    setTimeout(function() { setToasts(function(p) { return p.filter(function(t) { return t.id !== id }) }) }, 3000)");
c.push("  }");
c.push("  function addEvent(type) { setEvents(function(p) { return [...p, {type: type, time: Date.now()}] }) }");
c.push("  useEffect(function() {");
c.push("    fetchNotes()");
c.push("    var ch = supabase.channel('realtime-notes')");
c.push("      .on('postgres_changes', {event:'INSERT',schema:'public',table:'Note'}, function() { fetchNotes(); addToast('Note added!','success'); addEvent('add') })");
c.push("      .on('postgres_changes', {event:'UPDATE',schema:'public',table:'Note'}, function() { fetchNotes(); addToast('Note updated!','info'); addEvent('update') })");
c.push("      .on('postgres_changes', {event:'DELETE',schema:'public',table:'Note'}, function() { fetchNotes(); addToast('Note deleted!','delete'); addEvent('delete') })");
c.push("      .subscribe()");
c.push("    return function() { supabase.removeChannel(ch) }");
c.push("  }, [])");
c.push("  async function fetchNotes() {");
c.push("    const res = await fetch('/api/notes')");
c.push("    const data = await res.json()");
c.push("    setNotes(data)");
c.push("  }");
c.push("  async function handleSubmit(e) {");
c.push("    e.preventDefault()");
c.push("    setLoading(true)");
c.push("    if (editing) {");
c.push("      await fetch('/api/notes/'+editing.id, {method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify({title,content})})");
c.push("      setEditing(null)");
c.push("    } else {");
c.push("      await fetch('/api/notes', {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({title,content})})");
c.push("    }");
c.push("    setTitle(''); setContent(''); setLoading(false)");
c.push("  }");
c.push("  async function handleDelete(id) { await fetch('/api/notes/'+id, {method:'DELETE'}) }");
c.push("  function startEdit(note) { setEditing(note); setTitle(note.title); setContent(note.content) }");
c.push("  async function handleSignOut() { await supabase.auth.signOut(); router.push('/login') }");
c.push("  return (");
c.push("    <div className='min-h-screen bg-gray-100'>");
c.push("      <div className='fixed top-4 right-4 z-50 space-y-2'>");
c.push("        {toasts.map(function(t) { return <div key={t.id} className={'px-4 py-3 rounded-xl shadow-lg text-sm font-medium text-white '+(t.type==='success'?'bg-green-500':t.type==='delete'?'bg-red-500':'bg-blue-500')}>{t.message}</div> })}");
c.push("      </div>");
c.push("      <nav className='bg-white border-b px-6 py-4 flex justify-between items-center shadow-sm'>");
c.push("        <div><h1 className='text-xl font-bold text-gray-900'>My Notes</h1><p className='text-xs text-green-500 font-medium'>Live updates enabled</p></div>");
c.push("        <button onClick={handleSignOut} className='bg-red-500 hover:bg-red-600 text-white text-sm font-medium px-4 py-2 rounded-lg'>Sign Out</button>");
c.push("      </nav>");
c.push("      <div className='max-w-2xl mx-auto p-6'>");
c.push("        <div className='bg-white rounded-2xl shadow p-4 mb-6'>");
c.push("          <p className='text-sm font-semibold text-gray-700 mb-2'>Live Activity Chart</p>");
c.push("          <div className='flex gap-3 text-xs text-gray-500 mb-2'>");
c.push("            <span><span className='inline-block w-3 h-3 rounded bg-green-500 mr-1'></span>Added</span>");
c.push("            <span><span className='inline-block w-3 h-3 rounded bg-blue-500 mr-1'></span>Updated</span>");
c.push("            <span><span className='inline-block w-3 h-3 rounded bg-red-500 mr-1'></span>Deleted</span>");
c.push("          </div>");
c.push("          <ActivityCanvas events={events} />");
c.push("        </div>");
c.push("        <div className='bg-white rounded-2xl shadow p-6 mb-6'>");
c.push("          <h2 className='text-lg font-semibold text-gray-800 mb-4'>{editing ? 'Edit Note' : 'New Note'}</h2>");
c.push("          <form onSubmit={handleSubmit} className='space-y-4'>");
c.push("            <div><label className='block text-sm font-medium text-gray-700 mb-1'>Title</label>");
c.push("              <input placeholder='Enter a title...' value={title} onChange={function(e){setTitle(e.target.value)}} className='w-full border border-gray-300 rounded-lg px-4 py-3 text-gray-900 text-sm' required /></div>");
c.push("            <div><label className='block text-sm font-medium text-gray-700 mb-1'>Content</label>");
c.push("              <textarea placeholder='Write something...' value={content} onChange={function(e){setContent(e.target.value)}} className='w-full border border-gray-300 rounded-lg px-4 py-3 text-gray-900 text-sm h-28 resize-none' required /></div>");
c.push("            <div className='flex gap-3'>");
c.push("              <button type='submit' disabled={loading} className='bg-black hover:bg-gray-800 text-white font-medium px-5 py-2.5 rounded-lg text-sm disabled:opacity-50'>{loading?'Saving...':editing?'Update Note':'Add Note'}</button>");
c.push("              {editing ? <button type='button' onClick={function(){setEditing(null);setTitle('');setContent('')}} className='bg-gray-100 text-gray-700 px-5 py-2.5 rounded-lg text-sm'>Cancel</button> : null}");
c.push("            </div>");
c.push("          </form>");
c.push("        </div>");
c.push("        <div className='space-y-4'>");
c.push("          {notes.length===0 ? <div className='text-center py-16 text-gray-400'><p className='text-4xl mb-3'>No notes yet</p></div> : null}");
c.push("          {notes.map(function(note) { return (");
c.push("            <div key={note.id} className='bg-white rounded-2xl shadow p-5 border border-gray-100'>");
c.push("              <h3 className='font-semibold text-gray-900'>{note.title}</h3>");
c.push("              <p className='text-gray-600 text-sm mt-2'>{note.content}</p>");
c.push("              <div className='flex gap-3 mt-4'>");
c.push("                <button onClick={function(){startEdit(note)}} className='bg-blue-50 text-blue-600 text-sm px-4 py-1.5 rounded-lg'>Edit</button>");
c.push("                <button onClick={function(){handleDelete(note.id)}} className='bg-red-50 text-red-500 text-sm px-4 py-1.5 rounded-lg'>Delete</button>");
c.push("              </div>");
c.push("            </div>");
c.push("          )})}");
c.push("        </div>");
c.push("      </div>");
c.push("    </div>");
c.push("  )");
c.push("}");
fs.writeFileSync('app/dashboard/page.tsx', c.join('\n'), 'utf8');
console.log('Done!');
