var fs = require('fs');
var c = [];
c.push("'use client'");
c.push("import { useEffect, useState } from 'react'");
c.push("import { createClient } from '@/lib/supabase/client'");
c.push("import { useRouter } from 'next/navigation'");
c.push("");
c.push("export default function Dashboard() {");
c.push("  const [notes, setNotes] = useState([])");
c.push("  const [title, setTitle] = useState('')");
c.push("  const [content, setContent] = useState('')");
c.push("  const [editing, setEditing] = useState(null)");
c.push("  const [loading, setLoading] = useState(false)");
c.push("  const [toasts, setToasts] = useState([])");
c.push("  const supabase = createClient()");
c.push("  const router = useRouter()");
c.push("");
c.push("  function addToast(message, type) {");
c.push("    if (!type) type = 'success'");
c.push("    const id = Date.now()");
c.push("    setToasts(function(prev) { return [...prev, { id, message, type }] })");
c.push("    setTimeout(function() { setToasts(function(prev) { return prev.filter(function(t) { return t.id !== id }) }) }, 3000)");
c.push("  }");
c.push("");
c.push("  useEffect(function() {");
c.push("    fetchNotes()");
c.push("    var channel = supabase");
c.push("      .channel('realtime-notes')");
c.push("      .on('postgres_changes', { event: 'INSERT', schema: 'public', table: 'Note' }, function() { fetchNotes(); addToast('Note added!', 'success') })");
c.push("      .on('postgres_changes', { event: 'UPDATE', schema: 'public', table: 'Note' }, function() { fetchNotes(); addToast('Note updated!', 'info') })");
c.push("      .on('postgres_changes', { event: 'DELETE', schema: 'public', table: 'Note' }, function() { fetchNotes(); addToast('Note deleted!', 'delete') })");
c.push("      .subscribe()");
c.push("    return function() { supabase.removeChannel(channel) }");
c.push("  }, [])");
c.push("");
c.push("  async function fetchNotes() {");
c.push("    const res = await fetch('/api/notes')");
c.push("    const data = await res.json()");
c.push("    setNotes(data)");
c.push("  }");
c.push("");
c.push("  async function handleSubmit(e) {");
c.push("    e.preventDefault()");
c.push("    setLoading(true)");
c.push("    if (editing) {");
c.push("      await fetch('/api/notes/' + editing.id, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ title, content }) })");
c.push("      setEditing(null)");
c.push("    } else {");
c.push("      await fetch('/api/notes', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ title, content }) })");
c.push("    }");
c.push("    setTitle('')");
c.push("    setContent('')");
c.push("    setLoading(false)");
c.push("  }");
c.push("");
c.push("  async function handleDelete(id) {");
c.push("    await fetch('/api/notes/' + id, { method: 'DELETE' })");
c.push("  }");
c.push("");
c.push("  function startEdit(note) {");
c.push("    setEditing(note)");
c.push("    setTitle(note.title)");
c.push("    setContent(note.content)");
c.push("  }");
c.push("");
c.push("  async function handleSignOut() {");
c.push("    await supabase.auth.signOut()");
c.push("    router.push('/login')");
c.push("  }");
c.push("");
c.push("  return (");
c.push("    <div className='min-h-screen bg-gray-100'>");
c.push("      <div className='fixed top-4 right-4 z-50 space-y-2'>");
c.push("        {toasts.map(function(toast) { return (");
c.push("          <div key={toast.id} className={'px-4 py-3 rounded-xl shadow-lg text-sm font-medium text-white ' + (toast.type === 'success' ? 'bg-green-500' : toast.type === 'delete' ? 'bg-red-500' : 'bg-blue-500')}>");
c.push("            {toast.message}");
c.push("          </div>");
c.push("        )})}");
c.push("      </div>");
c.push("      <nav className='bg-white border-b border-gray-200 px-6 py-4 flex justify-between items-center shadow-sm'>");
c.push("        <div>");
c.push("          <h1 className='text-xl font-bold text-gray-900'>My Notes</h1>");
c.push("          <p className='text-xs text-green-500 font-medium'>Live updates enabled</p>");
c.push("        </div>");
c.push("        <button onClick={handleSignOut} className='bg-red-500 hover:bg-red-600 text-white text-sm font-medium px-4 py-2 rounded-lg transition'>Sign Out</button>");
c.push("      </nav>");
c.push("      <div className='max-w-2xl mx-auto p-6'>");
c.push("        <div className='bg-white rounded-2xl shadow p-6 mb-8'>");
c.push("          <h2 className='text-lg font-semibold text-gray-800 mb-4'>{editing ? 'Edit Note' : 'New Note'}</h2>");
c.push("          <form onSubmit={handleSubmit} className='space-y-4'>");
c.push("            <div>");
c.push("              <label className='block text-sm font-medium text-gray-700 mb-1'>Title</label>");
c.push("              <input placeholder='Enter a title...' value={title} onChange={function(e) { setTitle(e.target.value) }} className='w-full border border-gray-300 rounded-lg px-4 py-3 text-gray-900 placeholder-gray-400 focus:outline-none focus:ring-2 focus:ring-black text-sm' required />");
c.push("            </div>");
c.push("            <div>");
c.push("              <label className='block text-sm font-medium text-gray-700 mb-1'>Content</label>");
c.push("              <textarea placeholder='Write something...' value={content} onChange={function(e) { setContent(e.target.value) }} className='w-full border border-gray-300 rounded-lg px-4 py-3 text-gray-900 placeholder-gray-400 focus:outline-none focus:ring-2 focus:ring-black text-sm h-28 resize-none' required />");
c.push("            </div>");
c.push("            <div className='flex gap-3'>");
c.push("              <button type='submit' disabled={loading} className='bg-black hover:bg-gray-800 text-white font-medium px-5 py-2.5 rounded-lg text-sm transition disabled:opacity-50'>{loading ? 'Saving...' : editing ? 'Update Note' : 'Add Note'}</button>");
c.push("            </div>");
c.push("          </form>");
c.push("        </div>");
c.push("        <div className='space-y-4'>");
c.push("          {notes.length === 0 ? <div className='text-center py-16 text-gray-400'><p className='text-4xl mb-3'>No notes yet</p></div> : null}");
c.push("          {notes.map(function(note) { return (");
c.push("            <div key={note.id} className='bg-white rounded-2xl shadow p-5 border border-gray-100'>");
c.push("              <h3 className='font-semibold text-gray-900 text-base'>{note.title}</h3>");
c.push("              <p className='text-gray-600 text-sm mt-2 leading-relaxed'>{note.content}</p>");
c.push("              <div className='flex gap-3 mt-4'>");
c.push("                <button onClick={function() { startEdit(note) }} className='bg-blue-50 hover:bg-blue-100 text-blue-600 font-medium text-sm px-4 py-1.5 rounded-lg transition'>Edit</button>");
c.push("                <button onClick={function() { handleDelete(note.id) }} className='bg-red-50 hover:bg-red-100 text-red-500 font-medium text-sm px-4 py-1.5 rounded-lg transition'>Delete</button>");
c.push("              </div>");
c.push("            </div>");
c.push("          )})  }");
c.push("        </div>");
c.push("      </div>");
c.push("    </div>");
c.push("  )");
c.push("}");
fs.writeFileSync('app/dashboard/page.tsx', c.join('\n'), 'utf8');
console.log('Done!');
